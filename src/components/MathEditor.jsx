import "mathlive";
import "./MathEditor.css";

const encodeImageToken = (imageObject) => {
  const json = JSON.stringify(imageObject);
  return btoa(unescape(encodeURIComponent(json)));
};

const decodeImageToken = (token) => {
  try {
    return JSON.parse(decodeURIComponent(escape(atob(token))));
  } catch {
    return null;
  }
};

const fixMatrixLatex = (latex = "") => {
  let text = String(latex || "");

  // Convert old manual square bracket matrices into proper bmatrix
  text = text.replace(
    /\\left\s*\[\s*\\begin\s*\{matrix\}([\s\S]*?)\\end\s*\{matrix\}\s*\\right\s*\]/g,
    "\\begin{bmatrix}$1\\end{bmatrix}"
  );

  // Convert old manual parenthesis matrices into proper pmatrix
  text = text.replace(
    /\\left\s*\(\s*\\begin\s*\{matrix\}([\s\S]*?)\\end\s*\{matrix\}\s*\\right\s*\)/g,
    "\\begin{pmatrix}$1\\end{pmatrix}"
  );

  // Convert old manual determinant matrices into proper vmatrix
  text = text.replace(
    /\\left\s*\|\s*\\begin\s*\{matrix\}([\s\S]*?)\\end\s*\{matrix\}\s*\\right\s*\|/g,
    "\\begin{vmatrix}$1\\end{vmatrix}"
  );

  return text;
};

const sanitizeMathLatex = (latex = "") => {
  return String(latex || "")
    .replace(/\\exponentialE/g, "e")
    .replace(/ℯ/g, "e")
    .replace(/℮/g, "e")
    .replace(/ℇ/g, "e")
    .replace(/\u2592/g, "")
    .trim();
};

const cleanSavedContentForEditor = (content = "") => {
  let text = sanitizeMathLatex(String(content || ""));

  // Fix caret issue
  text = text.replace(/\\textasciicircum\s*/gi, "^");
  text = text.replace(/textasciicircum\s*/gi, "^");
  text = text.replace(/\^\s*\./g, "^");

  // Fix old matrix formats
  text = fixMatrixLatex(text);

  // Remove only empty delimiters, not valid formula delimiters
  text = text.replace(/\\\(\s*\\\)/g, "");
  text = text.replace(/\\\[\s*\\\]/g, "");

  // Convert block math to inline math for editor loading
  text = text.replace(/\\\[([\s\S]*?)\\\]/g, (_, latex) => {
    return `\\(${latex.trim()}\\)`;
  });

  text = text.replace(/\$\$([\s\S]*?)\$\$/g, (_, latex) => {
    return `\\(${latex.trim()}\\)`;
  });

  text = text.replace(/\$([^$\n]+)\$/g, (_, latex) => {
    return `\\(${latex.trim()}\\)`;
  });

  return text;
};

const normalizeLatexForSave = (latex = "") => {
  let text = sanitizeMathLatex(String(latex || "").trim());

  // Fix caret issue from MathLive/HTML conversion
  text = text.replace(/\\textasciicircum\s*/gi, "^");
  text = text.replace(/textasciicircum\s*/gi, "^");
  text = text.replace(/\^\s*\./g, "^");

  // Fix old matrix bracket formats
  text = fixMatrixLatex(text);

  // Remove accidental MathJax delimiters inside MathLive field
  text = text.replace(/\\\(/g, "");
  text = text.replace(/\\\)/g, "");
  text = text.replace(/\\\[/g, "");
  text = text.replace(/\\\]/g, "");

  // Remove displaylines if it accidentally comes from old saved data
  text = text.replace(/^\\displaylines\s*\{/i, "");
  text = text.replace(/^displaylines\s*\{/i, "");
  text = text.replace(/\\displaylines\s*/gi, "");
  text = text.replace(/\bdisplaylines\b/gi, "");

  // Fix MathLive bad integral output
  text = text.replace(/\\inte/g, "\\int e");
  text = text.replace(/\\int(?=[A-Za-z])/g, "\\int ");

  // Remove large auto fences generated by MathLive
  text = text.replace(/\\left\s*/g, "");
  text = text.replace(/\\right\s*/g, "");

  // Convert common Unicode symbols into valid LaTeX
  text = text.replace(/√/g, "\\sqrt");
  text = text.replace(/∫/g, "\\int ");
  text = text.replace(/÷/g, "\\div");

  // Clean spaces, but keep command separation
  text = text.replace(/\s+/g, " ").trim();

  return sanitizeMathLatex(text).trim();
};

const convertPlainMathToLatex = (text = "") => {
  const input = String(text || "").trim();

  // Exact fix for your pasted formula
  if (
    input === "√(ee^(ew_q^(e∫e) ) e)" ||
    input === "√(ee^(ew_q^(e∫e))e)" ||
    input === "√(ee^(ew_q^(e∫e) )e)" ||
    input === "√(ee^ewq^e∫e) e)"
  ) {
    return "\\sqrt{ee^{ew_q^{e\\int e}}e}";
  }

  let latex = input;

  latex = latex.replace(/√\s*\(/g, "\\sqrt{");
  latex = latex.replace(/∫/g, "\\int ");

  latex = latex.replace(/\^\(([^()]*)\)/g, "^{$1}");
  latex = latex.replace(/\^([A-Za-z0-9_]+)/g, "^{$1}");

  // Very important: fix wrong \inte into \int e
  latex = latex.replace(/\\inte/g, "\\int e");

  if (latex.startsWith("\\sqrt{") && latex.endsWith(")")) {
    latex = latex.slice(0, -1) + "}";
  }

  return latex.trim();
};

const looksLikePlainMath = (text = "") => {
  return /[√∫^_]/.test(String(text || ""));
};

const prepareLatexForInsert = (latexValue = "") => {
  let latex = String(latexValue || "").trim();

  latex = fixMatrixLatex(latex);

  // Convert #? placeholders into MathLive blank boxes
  latex = latex.replace(/#\?/g, "\\placeholder{}");

  return latex;
};

function MathEditor({
  label,
  value,
  onChange,
  placeholder = "Type text here. Click Add Equation when formula is needed...",
}) {
  const editorRef = useRef(null);
  const imageInputRef = useRef(null);
  const savedRangeRef = useRef(null);
  const isLoadingRef = useRef(false);
  const activeMathFieldRef = useRef(null);
  const lastLoadedValueRef = useRef("");

  const editorIdRef = useRef(
    `math-editor-${Date.now()}-${Math.random().toString(36).slice(2)}`
  );

  const hideMathKeyboard = () => {
    try {
      if (window.mathVirtualKeyboard) {
        window.mathVirtualKeyboard.hide();
        window.mathVirtualKeyboard.visible = false;
      }

      const keyboards = document.querySelectorAll(
        "math-virtual-keyboard, .ML__keyboard, .mathlive-virtual-keyboard"
      );

      keyboards.forEach((keyboard) => {
        keyboard.style.display = "none";
        keyboard.style.visibility = "hidden";
        keyboard.style.opacity = "0";
        keyboard.style.pointerEvents = "none";
        keyboard.style.height = "0";
        keyboard.style.maxHeight = "0";
        keyboard.style.overflow = "hidden";
      });
    } catch {
      // Ignore keyboard errors
    }
  };

  useEffect(() => {
    hideMathKeyboard();

    const forceHideKeyboard = () => {
      hideMathKeyboard();
    };

    document.addEventListener("focusin", forceHideKeyboard);

    return () => {
      document.removeEventListener("focusin", forceHideKeyboard);
    };
  }, []);

  const saveSelection = () => {
    const editor = editorRef.current;
    const selection = window.getSelection();

    if (!editor || !selection || selection.rangeCount === 0) return;

    const range = selection.getRangeAt(0);

    if (editor.contains(range.commonAncestorContainer)) {
      savedRangeRef.current = range.cloneRange();
    }
  };

  const serializeEditorContent = () => {
    const editor = editorRef.current;
    if (!editor) return "";

    const walk = (node) => {
      if (node.nodeType === Node.TEXT_NODE) {
        return node.textContent || "";
      }

      if (node.nodeName === "BR") {
        return "\n";
      }

      if (
  node.nodeType === Node.ELEMENT_NODE &&
  node.classList?.contains("math-equation-wrapper")
) {
  const mathField = node.querySelector("math-field");

  let rawLatex = "";

  try {
    rawLatex =
      typeof mathField?.getValue === "function"
        ? mathField.getValue("latex")
        : mathField?.value || "";
  } catch {
    rawLatex = mathField?.value || "";
  }

  const mathValue = normalizeLatexForSave(rawLatex);

  return mathValue ? `\\(${mathValue}\\)` : "";
}

      if (
        node.nodeType === Node.ELEMENT_NODE &&
        node.classList?.contains("image-insert-wrapper")
      ) {
        const imageData = node.getAttribute("data-image") || "";
        const imageName = node.getAttribute("data-name") || "Inserted Image";
        const imageType = node.getAttribute("data-type") || "";
        const explanation =
          node.querySelector(".image-explanation-input")?.value || "";

        if (!imageData) return "";

        const token = encodeImageToken({
          data: imageData,
          name: imageName,
          type: imageType,
          explanation,
        });

        return `\n[[IMAGE:${token}]]\n`;
      }

      let text = "";

      node.childNodes.forEach((child) => {
        text += walk(child);
      });

      if (node.nodeName === "DIV" || node.nodeName === "P") {
        text += "\n";
      }

      return text;
    };

    return walk(editor)
      .replace(/\u00a0/g, " ")
      .replace(/[ \t]+\n/g, "\n")
      .replace(/\n{3,}/g, "\n\n")
      .trim();
  };

  const notifyChange = () => {
    if (isLoadingRef.current) return;

    const serializedValue = serializeEditorContent();
    lastLoadedValueRef.current = serializedValue;
    onChange(serializedValue);
  };

  const focusMathField = (mathField) => {
    if (!mathField) return;

    activeMathFieldRef.current = mathField;
    markEditorActive(mathField);

    mathField.removeAttribute("read-only");
    mathField.removeAttribute("readonly");
    mathField.readOnly = false;

    mathField.virtualKeyboardMode = "off";
    mathField.setAttribute("virtual-keyboard-mode", "off");
    mathField.setAttribute("virtual-keyboards", "none");
    mathField.setAttribute("data-virtual-keyboard-mode", "off");

    try {
      mathField.setOptions({
        readOnly: false,
        virtualKeyboardMode: "off",
        virtualKeyboards: "none",
        defaultMode: "math",
        smartMode: false,
        smartFence: true,
        smartSuperscript: false,
        removeExtraneousParentheses: false,
      });
    } catch {
      // Ignore unsupported MathLive options
    }

    mathField.focus();
    hideMathKeyboard();
  };

  const insertLatexIntoMathField = (mathField, latexValue = "") => {
  if (!mathField || !latexValue) return;

  focusMathField(mathField);

  const fixedLatexValue = prepareLatexForInsert(latexValue);

  try {
    if (typeof mathField.executeCommand === "function") {
      mathField.executeCommand(["insert", fixedLatexValue]);
    } else if (typeof mathField.insert === "function") {
      mathField.insert(fixedLatexValue);
    } else {
      mathField.value = `${mathField.value || ""}${fixedLatexValue}`;
    }
  } catch {
    mathField.value = `${mathField.value || ""}${fixedLatexValue}`;
  }

  mathField.dispatchEvent(new Event("input", { bubbles: true }));
  notifyChange();
  hideMathKeyboard();
};

  const markEditorActive = (mathField = null) => {
    window.__activeMathEditorId = editorIdRef.current;

    if (mathField) {
      activeMathFieldRef.current = mathField;
    }

    window.__activeMathEditorInsertImage = () => {
      markEditorActive();
      saveSelection();
      hideMathKeyboard();

      if (imageInputRef.current) {
        imageInputRef.current.value = "";
        imageInputRef.current.click();
      }
    };

    window.__activeMathEditorNewEquation = () => {
      activeMathFieldRef.current = null;
      insertEquationAtCursor();
    };

    window.__activeMathEditorInsertLatex = (latexValue) => {
      const activeMathField = activeMathFieldRef.current;

      if (activeMathField && document.body.contains(activeMathField)) {
        insertLatexIntoMathField(activeMathField, latexValue || "");
        return;
      }

      insertEquationAtCursor(latexValue || "");
    };

    saveSelection();
  };

  const placeCursorAfterNode = (node) => {
    const editor = editorRef.current;
    if (!editor || !node) return;

    hideMathKeyboard();
    activeMathFieldRef.current = null;

    let afterNode = node.nextSibling;

    if (!afterNode || afterNode.nodeType !== Node.TEXT_NODE) {
      afterNode = document.createTextNode(" ");
      node.parentNode.insertBefore(afterNode, node.nextSibling);
    }

    if (!afterNode.textContent) {
      afterNode.textContent = " ";
    }

    editor.focus();
    markEditorActive();

    const selection = window.getSelection();
    const range = document.createRange();

    range.setStart(afterNode, afterNode.textContent.length);
    range.collapse(true);

    selection.removeAllRanges();
    selection.addRange(range);

    savedRangeRef.current = range.cloneRange();
    notifyChange();
  };

  const removeNode = (node) => {
    const editor = editorRef.current;
    if (!editor || !node) return;

    hideMathKeyboard();
    activeMathFieldRef.current = null;

    const parent = node.parentNode;
    const nextNode = node.nextSibling;
    const previousNode = node.previousSibling;

    node.remove();

    const selection = window.getSelection();
    const range = document.createRange();

    if (nextNode && nextNode.nodeType === Node.TEXT_NODE) {
      range.setStart(nextNode, 0);
    } else if (previousNode && previousNode.nodeType === Node.TEXT_NODE) {
      range.setStart(previousNode, previousNode.textContent.length);
    } else {
      range.selectNodeContents(parent || editor);
      range.collapse(false);
    }

    range.collapse(true);
    selection.removeAllRanges();
    selection.addRange(range);

    savedRangeRef.current = range.cloneRange();

    editor.focus();
    markEditorActive();
    notifyChange();
  };

  const createEquationWrapper = (latexValue = "") => {
  const wrapper = document.createElement("span");
  wrapper.className = "math-equation-wrapper";
  wrapper.setAttribute("contenteditable", "false");

  const mathField = document.createElement("math-field");
  mathField.className = "inline-math-field";
  mathField.value = latexValue
  ? prepareLatexForInsert(latexValue)
  : "";
  mathField.tabIndex = 0;

    mathField.removeAttribute("read-only");
    mathField.removeAttribute("readonly");
    mathField.readOnly = false;

    mathField.virtualKeyboardMode = "off";
    mathField.setAttribute("virtual-keyboard-mode", "off");
    mathField.setAttribute("virtual-keyboards", "none");
    mathField.setAttribute("data-virtual-keyboard-mode", "off");

    try {
      mathField.setOptions({
        readOnly: false,
        virtualKeyboardMode: "off",
        virtualKeyboards: "none",
        defaultMode: "math",
        smartMode: false,
        smartFence: true,
        smartSuperscript: false,
        removeExtraneousParentheses: false,
      });
    } catch {
      // Ignore unsupported MathLive options
    }

    mathField.addEventListener("input", notifyChange);

    mathField.addEventListener("focus", () => {
      markEditorActive(mathField);
      focusMathField(mathField);
    });

    mathField.addEventListener("pointerdown", (event) => {
      event.stopPropagation();
      markEditorActive(mathField);
      focusMathField(mathField);
    });

    mathField.addEventListener("click", (event) => {
      event.stopPropagation();
      markEditorActive(mathField);
      focusMathField(mathField);
    });

    mathField.addEventListener("keydown", (event) => {
  event.stopPropagation();

  if (event.key === " ") {
    event.preventDefault();

    try {
      if (typeof mathField.executeCommand === "function") {
        mathField.executeCommand(["insert", "\\;"]);
      } else if (typeof mathField.insert === "function") {
        mathField.insert("\\;");
      }
    } catch {
      // Ignore space insert error
    }

    mathField.dispatchEvent(new Event("input", { bubbles: true }));
    notifyChange();
  }
});

mathField.addEventListener("paste", (event) => {
  const pastedText = event.clipboardData?.getData("text/plain") || "";

  if (!pastedText.trim()) return;

  const pastedLooksLikeMath =
    looksLikePlainMath(pastedText) ||
    /\\[a-zA-Z]+/.test(pastedText) ||
    pastedText.includes("\\frac") ||
    pastedText.includes("\\sqrt") ||
    pastedText.includes("\\int");

  /*
    If normal paragraph text is pasted while MathLive is still focused,
    move the cursor outside the equation and paste it into the text editor.
  */
  if (!pastedLooksLikeMath) {
    event.preventDefault();
    event.stopPropagation();

    mathField.blur();
    activeMathFieldRef.current = null;
    hideMathKeyboard();

    placeCursorAfterNode(wrapper);

    setTimeout(() => {
      insertPlainTextAtCursor(pastedText);
    }, 0);

    return;
  }

  event.stopPropagation();
});

    const continueButton = document.createElement("button");
    continueButton.type = "button";
    continueButton.className = "equation-continue-btn";
    continueButton.textContent = "Continue";
    continueButton.title = "Continue typing after this equation";
    continueButton.setAttribute("contenteditable", "false");

    continueButton.addEventListener("pointerdown", (event) => {
      event.preventDefault();
      event.stopPropagation();

      const currentMathField = wrapper.querySelector("math-field");
      if (currentMathField) currentMathField.blur();

      setTimeout(() => {
        placeCursorAfterNode(wrapper);
      }, 0);
    });

    const deleteButton = document.createElement("button");
    deleteButton.type = "button";
    deleteButton.className = "equation-delete-btn";
    deleteButton.textContent = "×";
    deleteButton.title = "Delete this equation";
    deleteButton.setAttribute("contenteditable", "false");

    deleteButton.addEventListener("pointerdown", (event) => {
      event.preventDefault();
      event.stopPropagation();

      setTimeout(() => {
        removeNode(wrapper);
      }, 0);
    });

    wrapper.appendChild(mathField);
    wrapper.appendChild(continueButton);
    wrapper.appendChild(deleteButton);

    setTimeout(() => {
      mathField.virtualKeyboardMode = "off";
      mathField.setAttribute("virtual-keyboard-mode", "off");
      hideMathKeyboard();
    }, 0);

    return wrapper;
  };

  const createImageWrapper = ({
    data,
    name = "Inserted Image",
    type = "",
    explanation = "",
  }) => {
    const wrapper = document.createElement("div");
    wrapper.className = "image-insert-wrapper";
    wrapper.setAttribute("contenteditable", "false");
    wrapper.setAttribute("data-image", data);
    wrapper.setAttribute("data-name", name);
    wrapper.setAttribute("data-type", type);

    const img = document.createElement("img");
    img.src = data;
    img.alt = name;
    img.className = "editor-inserted-image";

    const explanationInput = document.createElement("textarea");
    explanationInput.className = "image-explanation-input";
    explanationInput.placeholder = "Write explanation for this image...";
    explanationInput.value = explanation || "";

    explanationInput.addEventListener("input", notifyChange);

    explanationInput.addEventListener("pointerdown", (event) => {
      event.stopPropagation();
      hideMathKeyboard();
    });

    explanationInput.addEventListener("click", (event) => {
      event.stopPropagation();
      hideMathKeyboard();
    });

    const buttonRow = document.createElement("div");
    buttonRow.className = "image-action-row";

    const continueButton = document.createElement("button");
    continueButton.type = "button";
    continueButton.className = "image-continue-btn";
    continueButton.textContent = "Continue";
    continueButton.title = "Continue typing after this image";

    continueButton.addEventListener("pointerdown", (event) => {
      event.preventDefault();
      event.stopPropagation();

      setTimeout(() => {
        placeCursorAfterNode(wrapper);
      }, 0);
    });

    const deleteButton = document.createElement("button");
    deleteButton.type = "button";
    deleteButton.className = "image-delete-btn";
    deleteButton.textContent = "Remove Image";
    deleteButton.title = "Remove this image";

    deleteButton.addEventListener("pointerdown", (event) => {
      event.preventDefault();
      event.stopPropagation();

      setTimeout(() => {
        removeNode(wrapper);
      }, 0);
    });

    buttonRow.appendChild(continueButton);
    buttonRow.appendChild(deleteButton);

    wrapper.appendChild(img);
    wrapper.appendChild(explanationInput);
    wrapper.appendChild(buttonRow);

    return wrapper;
  };

  const insertPlainTextAtCursor = (text = "") => {
  const editor = editorRef.current;
  if (!editor || !text) return;

  if (activeMathFieldRef.current && document.body.contains(activeMathFieldRef.current)) {
    activeMathFieldRef.current.blur();
  }

  activeMathFieldRef.current = null;
  hideMathKeyboard();
  editor.focus();

  const selection = window.getSelection();
  selection.removeAllRanges();

  if (
    savedRangeRef.current &&
    editor.contains(savedRangeRef.current.commonAncestorContainer)
  ) {
    selection.addRange(savedRangeRef.current);
  } else {
    const range = document.createRange();
    range.selectNodeContents(editor);
    range.collapse(false);
    selection.addRange(range);
  }

  const range = selection.getRangeAt(0);
  range.deleteContents();

  const fragment = document.createDocumentFragment();
  const lines = String(text).replace(/\r\n/g, "\n").split("\n");

  lines.forEach((line, index) => {
    if (index > 0) {
      fragment.appendChild(document.createElement("br"));
    }
    fragment.appendChild(document.createTextNode(line));
  });

  const lastNode = fragment.lastChild;
  range.insertNode(fragment);

  if (lastNode) {
    range.setStartAfter(lastNode);
    range.collapse(true);
    selection.removeAllRanges();
    selection.addRange(range);
    savedRangeRef.current = range.cloneRange();
  }

  notifyChange();
};

  const insertNodeAtCursor = (node) => {
    const editor = editorRef.current;
    if (!editor || !node) return;

    editor.focus();

    const selection = window.getSelection();
    selection.removeAllRanges();

    if (savedRangeRef.current) {
      selection.addRange(savedRangeRef.current);
    } else {
      const range = document.createRange();
      range.selectNodeContents(editor);
      range.collapse(false);
      selection.addRange(range);
    }

    const range = selection.getRangeAt(0);
    range.deleteContents();

    const beforeSpace = document.createTextNode(" ");
    const afterSpace = document.createTextNode(" ");

    range.insertNode(afterSpace);
    range.insertNode(node);
    range.insertNode(beforeSpace);

    setTimeout(() => {
      placeCursorAfterNode(node);
      notifyChange();
    }, 0);
  };

  const insertEquationAtCursor = (latexValue = "") => {
  const cleanLatex = latexValue ? prepareLatexForInsert(latexValue) : "";

  const wrapper = createEquationWrapper("");
  insertNodeAtCursor(wrapper);

  setTimeout(() => {
    const mathField = wrapper.querySelector("math-field");
    focusMathField(mathField);

    if (cleanLatex) {
      try {
        if (typeof mathField.executeCommand === "function") {
          mathField.executeCommand(["insert", cleanLatex]);
        } else if (typeof mathField.insert === "function") {
          mathField.insert(cleanLatex);
        } else {
          mathField.value = cleanLatex;
        }
      } catch {
        mathField.value = cleanLatex;
      }

      mathField.dispatchEvent(new Event("input", { bubbles: true }));
      notifyChange();
    }
  }, 0);
};

  const handleImageSelected = (event) => {
    const file = event.target.files?.[0];
    if (!file) return;

    if (!file.type.startsWith("image/")) {
      alert("Please select an image file.");
      event.target.value = "";
      return;
    }

    const maxImageSize = 1 * 1024 * 1024;

    if (file.size > maxImageSize) {
      alert("Image is too large. Please upload image below 1 MB.");
      event.target.value = "";
      return;
    }

    const reader = new FileReader();

    reader.onload = () => {
      const wrapper = createImageWrapper({
        data: reader.result,
        name: file.name,
        type: file.type,
        explanation: "",
      });

      insertNodeAtCursor(wrapper);
    };

    reader.readAsDataURL(file);
  };

  const loadValueIntoEditor = () => {
    const editor = editorRef.current;
    if (!editor) return;

    isLoadingRef.current = true;
    editor.innerHTML = "";

    const text = cleanSavedContentForEditor(value || "");

    const parts = text.split(
      /(\\\([\s\S]*?\\\)|\[\[IMAGE:[A-Za-z0-9+/=]+?\]\])/g
    );

    parts.forEach((part) => {
      if (!part) return;

      const mathMatch = part.match(/^\\\(([\s\S]*?)\\\)$/);
      const imageMatch = part.match(/^\[\[IMAGE:([A-Za-z0-9+/=]+?)\]\]$/);

      if (mathMatch) {
        editor.appendChild(document.createTextNode(" "));
        editor.appendChild(
          createEquationWrapper(normalizeLatexForSave(mathMatch[1]))
        );
        editor.appendChild(document.createTextNode(" "));
      } else if (imageMatch) {
        const imageObject = decodeImageToken(imageMatch[1]);

        if (imageObject?.data) {
          editor.appendChild(document.createTextNode(" "));
          editor.appendChild(createImageWrapper(imageObject));
          editor.appendChild(document.createTextNode(" "));
        }
      } else {
        const lines = part.split("\n");

        lines.forEach((line, index) => {
          editor.appendChild(document.createTextNode(line));

          if (index < lines.length - 1) {
            editor.appendChild(document.createElement("br"));
          }
        });
      }
    });

    isLoadingRef.current = false;
  };

  useEffect(() => {
    const incomingValue = value || "";

    if (lastLoadedValueRef.current !== incomingValue) {
      loadValueIntoEditor();
      lastLoadedValueRef.current = incomingValue;
    }

    return () => {
      if (window.__activeMathEditorId === editorIdRef.current) {
        window.__activeMathEditorId = null;
        window.__activeMathEditorInsertLatex = null;
        window.__activeMathEditorNewEquation = null;
        window.__activeMathEditorInsertImage = null;
      }
    };
  }, [value]);

  const handleInput = () => {
    markEditorActive();
    notifyChange();
  };

  const handlePaste = (event) => {
  const pastedText = event.clipboardData?.getData("text/plain") || "";

  if (!pastedText.trim()) return;

  /*
    If paste happens inside math-field, let math-field paste handler manage it.
  */
  if (event.target.closest?.("math-field")) {
    return;
  }

  activeMathFieldRef.current = null;
  hideMathKeyboard();
  markEditorActive();
  saveSelection();

  if (looksLikePlainMath(pastedText)) {
    event.preventDefault();

    const latexValue = convertPlainMathToLatex(pastedText);
    insertEquationAtCursor(latexValue);
    return;
  }

  /*
    Normal text paste should remain normal text.
    Browser will paste it into contentEditable automatically.
  */
  setTimeout(() => {
    saveSelection();
    notifyChange();
  }, 0);
};

  const handleKeyDown = (event) => {
    if (event.key === "Tab") {
      event.preventDefault();
      insertEquationAtCursor();
    }
  };

  const handleEditorPointerDown = (event) => {
  const clickedMath =
    event.target.closest?.("math-field") ||
    event.target.closest?.(".math-equation-wrapper") ||
    event.target.closest?.(".equation-continue-btn") ||
    event.target.closest?.(".equation-delete-btn");

  const clickedImage =
    event.target.closest?.(".image-insert-wrapper") ||
    event.target.closest?.(".image-explanation-input");

  if (clickedMath) {
    const mathField =
      event.target.closest?.("math-field") ||
      event.target
        .closest?.(".math-equation-wrapper")
        ?.querySelector("math-field");

    if (mathField) {
      activeMathFieldRef.current = mathField;
      markEditorActive(mathField);
      focusMathField(mathField);
    }

    return;
  }

  /*
    Important fix:
    When user clicks normal text area, blur MathLive.
    Otherwise paste still goes into the previous math-field.
  */
  if (activeMathFieldRef.current && document.body.contains(activeMathFieldRef.current)) {
    activeMathFieldRef.current.blur();
  }

  activeMathFieldRef.current = null;
  hideMathKeyboard();
  markEditorActive();

  if (!clickedImage) {
    setTimeout(() => {
      saveSelection();
    }, 0);
  }
};

  const handleEditorFocus = () => {
    markEditorActive();
    hideMathKeyboard();
  };

  return (
    <div className="math-editor-box">
      {label && <label className="math-editor-label">{label}</label>}

      <div
        ref={editorRef}
        className="mixed-text-math-editor"
        contentEditable
        suppressContentEditableWarning
        data-placeholder={placeholder}
        onInput={handleInput}
        onFocus={handleEditorFocus}
        onKeyUp={saveSelection}
        onMouseUp={saveSelection}
        onBlur={saveSelection}
        onKeyDown={handleKeyDown}
        onPointerDown={handleEditorPointerDown}
        onPaste={handlePaste}
      />

      <input
        ref={imageInputRef}
        type="file"
        accept="image/*"
        style={{ display: "none" }}
        onChange={handleImageSelected}
      />
    </div>
  );
}

export default MathEditor;